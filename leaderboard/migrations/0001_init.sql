CREATE TABLE IF NOT EXISTS scores (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, score_tenths INTEGER NOT NULL CHECK (score_tenths BETWEEN 0 AND 1000), created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX IF NOT EXISTS scores_order ON scores(score_tenths DESC,id ASC);
CREATE TABLE IF NOT EXISTS rate_limits (key TEXT PRIMARY KEY,day TEXT NOT NULL,used INTEGER NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS rate_limits_day ON rate_limits(day);
